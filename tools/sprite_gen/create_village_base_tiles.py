def main():
    filepath = os.path.join(ASSETS_DIR, TILESET_FILE)

    # Create backup
    backup_path = filepath + ".backup"
    if not os.path.exists(backup_path):
        shutil.copy2(filepath, backup_path)
        print(f"Backup created: {backup_path}")

    # Open existing tileset
    tileset = Image.open(filepath).convert("RGBA")
    print(f"Opened {TILESET_FILE}: {tileset.size[0]}x{tileset.size[1]}")

    # Place all base tiles
    for index, palette, grid, name in BASE_TILES:
        sprite = create_sprite(palette, grid)
        col = index % COLS
        row = index // COLS
        tileset.paste(sprite, (col * TILE_SIZE, row * TILE_SIZE))
        print(f"  Placed {name} at index {index} (col={col}, row={row})")

    # Place water tiles (indices 48-63)
    # Bit pattern: bit0=top, bit1=right, bit2=bottom, bit3=left
    for i in range(16):
        top = bool(i & 1)
        right = bool(i & 2)
        bottom = bool(i & 4)
        left = bool(i & 8)
        water_grid = create_water_tile(top, right, bottom, left)
        sprite = create_sprite(WATER_PALETTE, water_grid)
        index = 48 + i
        col = index % COLS
        row = index // COLS
        tileset.paste(sprite, (col * TILE_SIZE, row * TILE_SIZE))
        edges = []
        if top: edges.append("top")
        if right: edges.append("right")
        if bottom: edges.append("bottom")
        if left: edges.append("left")
        edge_str = "+".join(edges) if edges else "none"
        print(f"  Placed water_{edge_str} at index {index}")

    # Save
    tileset.save(filepath)
    print(f"\nSaved {TILESET_FILE}: {tileset.size[0]}x{tileset.size[1]}")
    print(f"Updated {len(BASE_TILES) + 16} tiles (indices 0-63)")
    print("Extended tiles (64+) were NOT modified.")



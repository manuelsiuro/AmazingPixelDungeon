def create_water_tile(top_shore, right_shore, bottom_shore, left_shore):
    """Create a water tile with optional shore edges on each side."""
    grid = [row[:] for row in WATER_BASE_GRID]

    # Add shore on top (rows 0-2)
    if top_shore:
        for x in range(16):
            grid[0][x] = 7
            grid[1][x] = 8 if x % 3 == 0 else 7
            grid[2][x] = 5 if x % 2 == 0 else 2

    # Add shore on bottom (rows 13-15)
    if bottom_shore:
        for x in range(16):
            grid[13][x] = 5 if x % 2 == 0 else 2
            grid[14][x] = 8 if x % 3 == 0 else 7
            grid[15][x] = 7

    # Add shore on left (cols 0-2)
    if left_shore:
        for y in range(16):
            grid[y][0] = 7
            grid[y][1] = 8 if y % 3 == 0 else 7
            grid[y][2] = 5 if y % 2 == 0 else 2

    # Add shore on right (cols 13-15)
    if right_shore:
        for y in range(16):
            grid[y][13] = 5 if y % 2 == 0 else 2
            grid[y][14] = 8 if y % 3 == 0 else 7
            grid[y][15] = 7

    return grid


